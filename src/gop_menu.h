static EFI_GRAPHICS_OUTPUT_BLT_PIXEL GuGopRgb(UINT32 rgb) {
  EFI_GRAPHICS_OUTPUT_BLT_PIXEL px;
  px.Blue = (UINT8)(rgb & 0xFFU);
  px.Green = (UINT8)((rgb >> 8) & 0xFFU);
  px.Red = (UINT8)((rgb >> 16) & 0xFFU);
  px.Reserved = 0U;
  return px;
}

static VOID GuGopFillRect(EFI_GRAPHICS_OUTPUT_PROTOCOL *gop, UINT32 rgb,
                          UINT32 x, UINT32 y, UINT32 w, UINT32 h) {
  if (!gop || !gop->Blt || w == 0U || h == 0U)
    return;
  EFI_GRAPHICS_OUTPUT_BLT_PIXEL px = GuGopRgb(rgb);
  (VOID)gop->Blt(gop, &px, EfiBltVideoFill, 0, 0, x, y, w, h, 0);
}

